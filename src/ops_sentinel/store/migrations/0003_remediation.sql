-- Remediation: proposed actions, approvals, executions, channel notifications and edge runners.

CREATE TABLE IF NOT EXISTS PROPOSED_ACTIONS (
    PROPOSAL_ID    VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    INCIDENT_ID    VARCHAR(26)   NOT NULL,
    ACTION_ID      VARCHAR(64)   NOT NULL,
    PARAMS         VARCHAR(200000),
    RISK           VARCHAR(10)   NOT NULL,
    RATIONALE      VARCHAR(20000),
    DECISION       VARCHAR(20)   NOT NULL, -- pending | auto | approved | rejected | denied | expired
    POLICY_REASON  VARCHAR(2000),
    QUORUM         DECIMAL(2,0)  NOT NULL,
    CREATED_AT     TIMESTAMP     NOT NULL,
    DECIDED_AT     TIMESTAMP
);

CREATE TABLE IF NOT EXISTS APPROVALS (
    APPROVAL_ID    VARCHAR(26)   NOT NULL PRIMARY KEY,
    PROPOSAL_ID    VARCHAR(26)   NOT NULL,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    APPROVER       VARCHAR(200)  NOT NULL,
    DECISION       VARCHAR(10)   NOT NULL, -- approve | reject
    CHANNEL        VARCHAR(100),
    CREATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS ACTION_EXECUTIONS (
    EXECUTION_ID   VARCHAR(26)   NOT NULL PRIMARY KEY,
    PROPOSAL_ID    VARCHAR(26)   NOT NULL,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    EXECUTOR       VARCHAR(200)  NOT NULL, -- engine:sql, engine:http, runner:<name>
    STATUS         VARCHAR(20)   NOT NULL, -- dispatched | running | succeeded | failed | verified | verify_failed
    ATTEMPTS       DECIMAL(3,0)  NOT NULL,
    OUTPUT_TEXT    VARCHAR(200000),
    STARTED_AT     TIMESTAMP     NOT NULL,
    FINISHED_AT    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS NOTIFICATIONS (
    NOTIFICATION_ID VARCHAR(26)  NOT NULL PRIMARY KEY,
    INCIDENT_ID    VARCHAR(26)   NOT NULL,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    CHANNEL        VARCHAR(100)  NOT NULL,
    EXTERNAL_REF   VARCHAR(500),
    PURPOSE        VARCHAR(20)   NOT NULL, -- notify | approve | update
    CREATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS RUNNERS (
    RUNNER_ID      VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    RUNNER_NAME    VARCHAR(100)  NOT NULL,
    ENVIRONMENT    VARCHAR(100)  NOT NULL,
    TOKEN_SHA256   VARCHAR(64)   NOT NULL, -- the token itself is shown once and never stored
    LAST_SEEN_AT   TIMESTAMP,
    CREATED_AT     TIMESTAMP     NOT NULL,
    REVOKED_AT     TIMESTAMP
);
