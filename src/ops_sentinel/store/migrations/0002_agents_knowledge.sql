-- Agent runs and their steps (the subagent tree), evidence blobs, the knowledge base and incident memory.
-- Embeddings are base64 float32 (see udf_lib/vector.py) and searched with the VECTOR_COSINE UDF.

CREATE TABLE IF NOT EXISTS AGENT_RUNS (
    RUN_ID         VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    INCIDENT_ID    VARCHAR(26),
    PARENT_RUN_ID  VARCHAR(26),   -- set for subagents
    AGENT_NAME     VARCHAR(100)  NOT NULL,
    MODEL          VARCHAR(200),
    STATUS         VARCHAR(20)   NOT NULL, -- running | succeeded | failed | budget_exhausted
    INPUT_TOKENS   DECIMAL(18,0) NOT NULL,
    OUTPUT_TOKENS  DECIMAL(18,0) NOT NULL,
    COST_USD       DECIMAL(12,6) NOT NULL,
    RESULT_JSON    VARCHAR(2000000),
    STARTED_AT     TIMESTAMP     NOT NULL,
    FINISHED_AT    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS AGENT_STEPS (
    STEP_ID        VARCHAR(26)   NOT NULL PRIMARY KEY,
    RUN_ID         VARCHAR(26)   NOT NULL,
    STEP_NO        DECIMAL(5,0)  NOT NULL,
    KIND           VARCHAR(20)   NOT NULL, -- llm | tool | delegate | answer
    TOOL_NAME      VARCHAR(200),
    ARGUMENTS      VARCHAR(200000),
    RESULT_SUMMARY VARCHAR(200000),
    EVIDENCE_ID    VARCHAR(26),
    DURATION_MS    DECIMAL(12,0),
    CREATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS EVIDENCE (
    EVIDENCE_ID    VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    INCIDENT_ID    VARCHAR(26),
    SOURCE_NAME    VARCHAR(200)  NOT NULL,
    CONTENT_TYPE   VARCHAR(50)   NOT NULL,
    CONTENT        VARCHAR(2000000),
    CREATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS KNOWLEDGE_DOCUMENTS (
    DOCUMENT_ID    VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    SOURCE_NAME    VARCHAR(100)  NOT NULL,
    URI            VARCHAR(2000) NOT NULL,
    TITLE          VARCHAR(500),
    CONTENT_HASH   VARCHAR(64)   NOT NULL,
    PINNED         BOOLEAN       NOT NULL,
    METADATA       VARCHAR(20000),
    UPDATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS KNOWLEDGE_CHUNKS (
    CHUNK_ID       VARCHAR(26)   NOT NULL PRIMARY KEY,
    DOCUMENT_ID    VARCHAR(26)   NOT NULL,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    CHUNK_NO       DECIMAL(9,0)  NOT NULL,
    HEADING        VARCHAR(1000),
    CONTENT        VARCHAR(200000) NOT NULL,
    EMBEDDING      VARCHAR(2000000),
    EMBEDDING_MODEL VARCHAR(200),
    TOKEN_COUNT    DECIMAL(9,0)
);

CREATE TABLE IF NOT EXISTS INCIDENT_MEMORIES (
    MEMORY_ID      VARCHAR(26)   NOT NULL PRIMARY KEY,
    WORKSPACE_ID   VARCHAR(100)  NOT NULL,
    INCIDENT_ID    VARCHAR(26)   NOT NULL,
    FINGERPRINT    VARCHAR(64)   NOT NULL,
    SERVICE        VARCHAR(200),
    SUMMARY        VARCHAR(20000) NOT NULL,
    ROOT_CAUSE     VARCHAR(20000),
    ACTION_ID      VARCHAR(64),
    OUTCOME        VARCHAR(20),
    FEEDBACK       VARCHAR(4000),
    EMBEDDING      VARCHAR(2000000),
    CREATED_AT     TIMESTAMP     NOT NULL
);
