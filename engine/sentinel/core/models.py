"""Domain models shared by ingest, the store, the worker and the API.

Ids are generated by the application (time-ordered, sortable, 26 characters) rather than by Exasol IDENTITY columns:
several api and worker replicas insert concurrently, Exasol has no RETURNING clause, and a client-generated id lets a
retried insert stay idempotent.
"""
import os
import time
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field

_CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def new_id() -> str:
    """A ULID: 48 bits of millisecond time and 80 random bits, Crockford base32. Sorts by creation time."""
    value = (int(time.time() * 1000) << 80) | int.from_bytes(os.urandom(10), "big")
    return "".join(_CROCKFORD[(value >> shift) & 31] for shift in range(125, -1, -5))


def utcnow() -> datetime:
    """Naive UTC, which is what Exasol TIMESTAMP columns store."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class Severity(str, Enum):
    INFO = "info"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"

    @property
    def rank(self) -> int:
        return list(Severity).index(self)

    @classmethod
    def parse(cls, value: object, default: "Severity | None" = None) -> "Severity":
        """Maps the many spellings alert tools use (P1, crit, warning, error, ...) onto the five levels."""
        text = str(value or "").strip().lower()
        aliases = {
            "p1": cls.CRITICAL, "sev1": cls.CRITICAL, "crit": cls.CRITICAL, "fatal": cls.CRITICAL, "page": cls.CRITICAL,
            "p2": cls.HIGH, "sev2": cls.HIGH, "error": cls.HIGH, "major": cls.HIGH,
            "p3": cls.MEDIUM, "sev3": cls.MEDIUM, "warning": cls.MEDIUM, "warn": cls.MEDIUM,
            "p4": cls.LOW, "sev4": cls.LOW, "minor": cls.LOW,
            "p5": cls.INFO, "none": cls.INFO, "ok": cls.INFO, "informational": cls.INFO,
        }
        if text in aliases:
            return aliases[text]
        try:
            return cls(text)
        except ValueError:
            return default if default is not None else cls.MEDIUM


class IncidentStatus(str, Enum):
    OPEN = "open"
    TRIAGING = "triaging"
    INVESTIGATING = "investigating"
    AWAITING_APPROVAL = "awaiting_approval"
    REMEDIATING = "remediating"
    VERIFYING = "verifying"
    RESOLVED = "resolved"
    SUPPRESSED = "suppressed"
    REJECTED = "rejected"
    FAILED = "failed"
    ESCALATED = "escalated"

    @property
    def is_open(self) -> bool:
        return self not in CLOSED_STATUSES


CLOSED_STATUSES = frozenset({IncidentStatus.RESOLVED, IncidentStatus.SUPPRESSED, IncidentStatus.REJECTED})


class Signal(BaseModel):
    """One normalized observation from a source. Every source plugin produces these and nothing else."""

    source: str = Field(min_length=1, max_length=100)
    fingerprint: str = Field(min_length=1, max_length=64)
    summary: str = Field(max_length=2000)
    severity: Severity = Severity.MEDIUM
    labels: dict[str, str] = Field(default_factory=dict)
    payload: dict[str, Any] = Field(default_factory=dict)
    # A source that reports recoveries (Alertmanager "resolved") marks them so they close instead of open incidents.
    resolved: bool = False
    observed_at: datetime = Field(default_factory=utcnow)


class Incident(BaseModel):
    incident_id: str
    workspace_id: str
    fingerprint: str
    title: str
    severity: Severity
    status: IncidentStatus
    service: str | None = None
    source: str | None = None  # the source of the signal that opened it
    labels: dict[str, str] = Field(default_factory=dict)
    signal_count: int = 1
    opened_at: datetime
    updated_at: datetime
    resolved_at: datetime | None = None
